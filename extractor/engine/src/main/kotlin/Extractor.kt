import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.ObjectMapper
import org.jetbrains.kotlin.cli.jvm.compiler.KotlinCoreEnvironment
import org.jetbrains.kotlin.cli.jvm.compiler.EnvironmentConfigFiles
import org.jetbrains.kotlin.config.CompilerConfiguration
import org.jetbrains.kotlin.psi.KtFile
import org.jetbrains.kotlin.psi.KtPsiFactory
import org.jetbrains.kotlin.psi.KtDeclaration
import org.jetbrains.kotlin.psi.KtNamedDeclaration
import org.jetbrains.kotlin.psi.KtImportDirective
import org.jetbrains.kotlin.psi.KtPackageDirective
import org.jetbrains.kotlin.utils.PathUtil
import org.jetbrains.kotlin.com.intellij.openapi.util.Disposer
import java.io.File

private val mapper = ObjectMapper()

fun main(args: Array<String>) {
    val source = File(args.getOrElse(0) { "source/MainActivity.kt" })
    val mappingFile = File(args.getOrElse(1) { "config/module-mapping.json" })
    val output = File(args.getOrElse(2) { "build/extracted" })
    require(source.isFile) { "Source file not found: ${source.path}" }
    require(mappingFile.isFile) { "Mapping file not found: ${mappingFile.path}" }

    val mapping = mapper.readTree(mappingFile)
    val declarationMap = linkedMapOf<String, String>()
    val packageMap = linkedMapOf<String, String>()
    readMappings(mapping, declarationMap, packageMap)

    val disposable = Disposer.newDisposable()
    try {
        val env = KotlinCoreEnvironment.createForProduction(disposable, CompilerConfiguration(), EnvironmentConfigFiles.JVM_CONFIG_FILES)
        val psiFactory = KtPsiFactory(env.project, false)
        val parsed = psiFactory.createFile(source.name, source.readText())
        val packageName = parsed.packageDirective?.fqName?.asString().orEmpty()
        val imports = parsed.importDirectives.map { it.text }.joinToString("\n")
        val declarations = parsed.declarations.filterIsInstance<KtNamedDeclaration>()
        val report = mutableListOf<Map<String, Any?>>()
        val grouped = linkedMapOf<String, MutableMap<String, MutableList<String>>>()
        var unmapped = 0

        for (declaration in declarations) {
            val name = declaration.name ?: "<anonymous:${declaration.javaClass.simpleName}>"
            val module = declarationMap[name]
            val text = declaration.text
            if (module == null) {
                unmapped++
                report += mapOf("name" to name, "kind" to declaration.javaClass.simpleName, "status" to "UNMAPPED", "sourceStart" to declaration.textRange.startOffset, "sourceEnd" to declaration.textRange.endOffset)
            } else {
                grouped.getOrPut(module) { linkedMapOf() }.getOrPut(name) { mutableListOf() }.add(text)
                report += mapOf("name" to name, "kind" to declaration.javaClass.simpleName, "module" to module, "status" to "EXTRACTED", "sourceStart" to declaration.textRange.startOffset, "sourceEnd" to declaration.textRange.endOffset)
            }
        }

        output.deleteRecursively()
        output.mkdirs()
        for ((module, items) in grouped) {
            val targetPackage = packageMap[module] ?: packageName
            val packagePath = targetPackage.replace('.', '/')
            val moduleRoot = File(output, module)
            val dest = File(moduleRoot, "src/main/kotlin/$packagePath")
            dest.mkdirs()
            for ((name, bodies) in items) {
                val safe = name.replace(Regex("[^A-Za-z0-9_]"), "_")
                val file = File(dest, "$safe.kt")
                val header = buildString {
                    append("// GENERATED BY MRIS EXTRACTION ENGINE. REVIEW BEFORE INTEGRATION.\n")
                    if (targetPackage.isNotBlank()) append("package $targetPackage\n\n")
                    if (imports.isNotBlank()) append(imports).append("\n\n")
                }
                file.writeText(header + bodies.joinToString("\n\n") + "\n")
            }
        }
        mapper.writeValue(File(output, "extraction-report.json"), mapOf("source" to source.path, "sourcePackage" to packageName, "declarationCount" to declarations.size, "mappedCount" to declarations.size - unmapped, "unmappedCount" to unmapped, "modules" to grouped.keys, "declarations" to report))
        File(output, "README.md").writeText("""# Generated extraction staging output

This is a first-pass PSI-based declaration extraction. It preserves declaration text and copies original imports into each generated file. It does **not** resolve symbols, repair visibility, rewrite imports, or guarantee a successful Android build. Review and dependency analysis are required before integrating these files.

Declarations found: ${declarations.size}
Mapped: ${declarations.size - unmapped}
Unmapped: $unmapped
Modules: ${grouped.keys.joinToString()}
""")
        println("PSI extraction complete: ${declarations.size} declarations; ${declarations.size - unmapped} mapped; $unmapped unmapped. Output: ${output.path}")
    } finally {
        Disposer.dispose(disposable)
    }
}

private fun readMappings(root: JsonNode, declarations: MutableMap<String, String>, packages: MutableMap<String, String>) {
    // Supported format A: {"declarations":{"Name":"module"},"modules":{"module":{"package":"..."}}}
    root.path("declarations").takeIf { it.isObject }?.fields()?.forEach { (name, node) ->
        if (node.isTextual) declarations[name] = node.asText()
        else if (node.isObject && node.path("module").isTextual) declarations[name] = node.path("module").asText()
    }
    root.path("modules").takeIf { it.isObject }?.fields()?.forEach { (module, node) ->
        node.path("package").takeIf { it.isTextual }?.asText()?.let { packages[module] = it }
        node.path("declarations").takeIf { it.isArray }?.forEach { declarations[it.asText()] = module }
    }
    // Supported format B: {"mapping":{"Name":"module"}} or plain {"Name":"module"}
    root.path("mapping").takeIf { it.isObject }?.fields()?.forEach { (name, node) -> if (node.isTextual) declarations[name] = node.asText() }
    if (root.isObject && !root.has("declarations") && !root.has("modules") && !root.has("mapping")) {
        root.fields().forEach { (name, node) -> if (node.isTextual) declarations[name] = node.asText() }
    }
}
